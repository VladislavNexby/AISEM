def size_corr (Gray_Img:np.ndarray, window_size = 10, epsilon = 0.02)->tuple:
  #Autocorr_self
  lags_c1_0, c1_0 = cor_by_size(Gray_Img,np.shape(Gray_Img)[0],np.shape(Gray_Img)[1], axis=0)
  lags_c2_0, c2_0 = cor_by_size(Gray_Img,np.shape(Gray_Img)[0],np.shape(Gray_Img)[1], axis=1)

  delta_x_1 = np.zeros(window_size)
  delta_y_1 = np.zeros(window_size)

  sigma_x = np.zeros(window_size)
  sigma_y = np.zeros(window_size)

  for i in range(window_size):

    scale = i+1

    x = round(np.shape(Gray_Img)[0]*scale/100)
    y = round(np.shape(Gray_Img)[0]*scale/100)

    lags_c1, c1 = cor_by_size(Gray_Img,x,y, axis=0)
    lags_c2, c2 = cor_by_size(Gray_Img,x,y, axis=1)

    d_c1=c1_0[lags_c1_0[-1]-lags_c1[-1]:lags_c1_0[-1]+lags_c1[-1]+1]-c1
    d_c2=c2_0[lags_c2_0[-1]-lags_c2[-1]:lags_c2_0[-1]+lags_c2[-1]+1]-c2

    delta_x_1[i] = np.mean(d_c1)
    delta_y_1[i] = np.mean(d_c2)

    sigma_x[i] = np.sqrt(np.sum((d_c1-delta_x_1[i])**2)/np.shape(d_c1)[0])
    sigma_y[i] = np.sqrt(np.sum((d_c2-delta_y_1[i])**2)/np.shape(d_c2)[0])

    sigma_x_smooth = np.convolve(sigma_x, np.ones(window_size)/window_size, mode='valid')
    sigma_y_smooth = np.convolve(sigma_y, np.ones(window_size)/window_size, mode='valid')

  while sigma_x_smooth[-1] >= epsilon:

    i+=1
    scale = i+1

    x = round(np.shape(Gray_Img)[0]*scale/100)
    y = round(np.shape(Gray_Img)[0]*scale/100)

    lags_c1, c1 = cor_by_size(Gray_Img,x,y, axis=0)
    lags_c2, c2 = cor_by_size(Gray_Img,x,y, axis=1)

    d_c1=c1_0[lags_c1_0[-1]-lags_c1[-1]:lags_c1_0[-1]+lags_c1[-1]+1]-c1
    d_c2=c2_0[lags_c2_0[-1]-lags_c2[-1]:lags_c2_0[-1]+lags_c2[-1]+1]-c2

    delta_x_1 = np.append(delta_x_1,np.mean(d_c1))
    delta_y_1 = np.append(delta_x_1,np.mean(d_c2))

    sigma_x = np.append(sigma_x,np.sqrt(np.sum((d_c1-delta_x_1[i])**2)/np.shape(d_c1)[0]))
    sigma_y = np.append(sigma_y,np.sqrt(np.sum((d_c2-delta_y_1[i])**2)/np.shape(d_c2)[0]))

    sigma_x_smooth = np.convolve(sigma_x, np.ones(window_size)/window_size, mode='valid')
    sigma_y_smooth = np.convolve(sigma_y, np.ones(window_size)/window_size, mode='valid')

  x2 = np.linspace(window_size//2+1, i-window_size//2, i-window_size+2)
  closest_value = x2[np.abs(sigma_x_smooth - epsilon).argmin()]
  scale = closest_value

  x = round(np.shape(Gray_Img)[0]*scale/100)
  y = round(np.shape(Gray_Img)[0]*scale/100)
  return (x,y)

