def cor_by_size (fig:np.ndarray ,x:int, y:int, axis = Literal[0, 1])->tuple:
  # Dimensions
  d = fig[0:x, 0:y]
  N, M = d.shape

  # Mean and std for normalization
  m = np.mean(d)
  s = np.std(d)
  d_norm = (d - m) / s

  с_all = {
      0:[correlate(row, row, mode='full') / len(row) for row in d_norm],
      1:[correlate(col, col, mode='full') / len(col) for col in d_norm.T]
  }
  c = np.mean(с_all[axis], axis=0)

  lags_c = {
      0:np.arange(-M + 1, M),
      1:np.arange(-N + 1, N)
  }

  c /= np.max(c)
  return (lags_c[axis],c)

